class Admin(BaseHTTPRequestHandler):
    server_version = 'JocoAdmin'

    def log_message(self, fmt, *args):
        sys.stderr.write('admin: %s %s\n' % (self.headers.get('X-Joco-User', '-'), fmt % args))

    @property
    def user(self):
        return self.headers.get('X-Joco-User', '')

    def token(self):
        with open(SECRET) as handle:
            return hmac.new(handle.read().encode(), self.user.encode(), hashlib.sha256).hexdigest()

    def guard(self):
        state = load_state()
        if not self.user or self.user not in state['mentors']:
            self.page('Mentors only', '<section><h2>Mentors only</h2><p>This page is for mentors. Students do everything from SOLIDWORKS.</p></section>', '', status=403)
            return None
        return state

    # ---------- FRCDesignLib API for the add-in (any signed-in student) ----------

    def frc_api(self, method):
        path = urlsplit(self.path).path
        if not self.user or self.user == PUBLISHER or self.headers.get('X-Joco-Client') != 'addin':
            return self.reply(403, 'Not allowed.')
        try:
            parts = path[len('/admin/api/frcdesign/'):].split('/')
            if method == 'GET' and parts[0] == 'search':
                return self.json_reply({'results': frcdesign.search(parse_qs(urlsplit(self.path).query).get('q', [''])[0])})
            if method == 'GET' and parts[0] == 'item' and len(parts) == 2:
                return self.json_reply(frcdesign.details(parts[1]))
            if method == 'GET' and parts[0] == 'thumb' and len(parts) == 2:
                size = parse_qs(urlsplit(self.path).query).get('size', ['300x300'])[0]
                data, kind = frcdesign.thumbnail(parts[1], '70x40' if size == '70x40' else '300x300')
                return self.bytes_reply(data, kind, 'public, max-age=86400')
            if method == 'GET' and parts[0] == 'download' and len(parts) == 2:
                data, name = frcdesign.download(self.user, parts[1], self.headers.get('X-Joco-Token', ''))
                return self.bytes_reply(data, 'application/octet-stream', 'no-store', name)
            if method == 'POST' and parts[0] in ('claim', 'complete', 'abandon'):
                body = json.loads(self.rfile.read(min(int(self.headers.get('Content-Length', '0')), 65536)) or b'{}')
                with Locked():
                    if parts[0] == 'claim':
                        return self.json_reply(frcdesign.claim(self.user, str(body.get('id', '')), body.get('configuration') or {},
                                                               str(body.get('client', ''))[:64]))
                    if parts[0] == 'complete':
                        return self.json_reply(frcdesign.complete(self.user, str(body.get('fingerprint', '')), str(body.get('token', ''))))
                    return self.json_reply(frcdesign.abandon(self.user, str(body.get('fingerprint', '')), str(body.get('token', ''))))
            return self.reply(404, 'Unknown request.')
        except frcdesign.FrcError as exc:
            return self.reply(exc.status, str(exc))
        except ValueError:
            return self.reply(400, 'Bad request.')

    def json_reply(self, value):
        return self.bytes_reply(json.dumps(value).encode(), 'application/json', 'no-store')

    def bytes_reply(self, data, kind, cache, filename=None):
        self.send_response(200)
        self.send_header('Content-Type', kind)
        self.send_header('Content-Length', str(len(data)))
        self.send_header('Cache-Control', cache)
        if filename:
            self.send_header('Content-Disposition', 'attachment; filename="%s"' % re.sub(r'[^A-Za-z0-9 ._()&+,-]', '_', filename))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if urlsplit(self.path).path.startswith('/admin/api/frcdesign/'):
            return self.frc_api('GET')
        state = self.guard()
        if state is None:
            return
        path = urlsplit(self.path).path.rstrip('/')
        query = parse_qs(urlsplit(self.path).query)
        notice = query.get('ok', [''])[0]
        error = query.get('error', [''])[0]
        self.query = query
        pages = {'/admin': self.home, '/admin/locks': self.locks_page, '/admin/library': self.library_page, '/admin/users': self.users_page,
                 '/admin/addin': self.addin_page, '/admin/undo': self.undo_page}
        if path not in pages:
            self.send_error(404)
            return
        try:
            body = pages[path](state)
        except Refused as exc:
            body, error = '', str(exc)
        banner = ''
        if notice:
            banner = '<div class="notice ok">' + esc(notice) + '</div>'
        if error:
            banner = '<div class="notice bad">' + esc(error) + '</div>'
        self.page({'/admin': 'Seasons', '/admin/locks': 'Locks', '/admin/library': 'Library', '/admin/users': 'Accounts', '/admin/addin': 'Add-in',
                   '/admin/undo': 'Undo a submit'}[path], banner + body, path)

    def do_POST(self):
        if urlsplit(self.path).path == '/admin/api/stage-addin':
            return self.stage()
        if urlsplit(self.path).path == '/admin/api/heartbeat':
            return self.heartbeat()
        if urlsplit(self.path).path.startswith('/admin/api/frcdesign/'):
            return self.frc_api('POST')
        if urlsplit(self.path).path == '/account/setup':
            return self.account_setup()
        if urlsplit(self.path).path == '/account/request':
            return self.account_request()
        if urlsplit(self.path).path == '/admin/api/password':
            return self.password_change()
        state = self.guard()
        if state is None:
            return
        back = urlsplit(self.path).path.rstrip('/') or '/admin'
        if back not in ('/admin', '/admin/locks', '/admin/library', '/admin/users', '/admin/addin'):
            back = '/admin'
        try:
            # Browsers resend Basic credentials automatically: require same-origin plus a per-user token.
            origin = self.headers.get('Origin') or self.headers.get('Referer') or ''
            host = self.headers.get('X-Forwarded-Host', self.headers.get('Host', '')).split(',')[0].strip()
            if urlsplit(origin).netloc != host:
                raise Refused('Request blocked: it did not come from this page.')
            length = int(self.headers.get('Content-Length', '0'))
            if length > MAX_UPLOAD + 65536:
                raise Refused('Upload is larger than 100 MB. Add big assemblies from SOLIDWORKS with Submit instead.')
            raw = self.rfile.read(length)
            kind = self.headers.get('Content-Type', '')
            if kind.startswith('multipart/form-data'):
                fields = self.multipart(kind, raw)
                if not hmac.compare_digest(fields.get('token', b'').decode(), self.token()):
                    raise Refused('Your page expired. Reload and try again.')
                with Locked():
                    message = upload(self.user, fields)
            else:
                form = {k: v[0] for k, v in parse_qs(raw.decode('utf-8'), keep_blank_values=True).items()}
                if not hmac.compare_digest(form.get('token', ''), self.token()):
                    raise Refused('Your page expired. Reload and try again.')
                with Locked():
                    message = act(self.user, form)
            self.redirect(back + '?ok=' + quote(message))
        except Refused as exc:
            self.redirect(back + '?error=' + quote(str(exc)[:600]))

