class Refused(Exception):
    """A request that was understood but not allowed; shown to the mentor."""


def run(*args, stdin=None):
    result = subprocess.run(args, input=stdin, capture_output=True)
    if result.returncode != 0:
        raise Refused((result.stderr or result.stdout).decode('utf-8', 'replace').strip() or 'Command failed: ' + args[0])
    return result.stdout.decode('utf-8', 'replace')


class Locked:
    """Serialize changes across web threads and `podman exec` maintenance."""
    def __enter__(self):
        _mutex.acquire()
        self.handle = open(os.path.join(CONFIG, '.admin.lock'), 'w')
        fcntl.flock(self.handle, fcntl.LOCK_EX)

    def __exit__(self, *_):
        fcntl.flock(self.handle, fcntl.LOCK_UN)
        self.handle.close()
        _mutex.release()


def write_atomic(path, text, mode=0o640):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, temp = tempfile.mkstemp(dir=os.path.dirname(path))
    with os.fdopen(fd, 'w') as handle:
        handle.write(text)
    os.chmod(temp, mode)
    os.replace(temp, path)


# ---------- state ----------

def repositories():
    # Dot-folders hold deleted seasons; they are not served or backed up.
    return sorted(n for n in os.listdir(REPOS) if not n.startswith('.') and os.path.isfile(os.path.join(REPOS, n, 'format')))


def load_state():
    try:
        with open(STATE) as handle:
            state = json.load(handle)
    except FileNotFoundError:
        seasons = [n for n in repositories() if SEASON.match(n)]
        state = {'active': seasons[-1] if seasons else None, 'archived': [], 'mentors': []}
    state.setdefault('archived', [])
    state.setdefault('mentors', [])
    return state


def save_state(state):
    write_atomic(STATE, json.dumps(state, indent=2) + '\n')
    publish(state)


def uuid(name):
    return run('svnlook', 'uuid', os.path.join(REPOS, name)).strip()


def publish(state):
    """Regenerate SVN access rules and the catalog the add-in reads."""
    # "~name" = every signed-in account except the release uploader.
    rules = ['# Generated by joco.py from state.json; edit through the admin page.', '[/]', '~%s = rw' % PUBLISHER, '']
    for name in state['archived']:
        rules += ['[%s:/]' % name, '~%s = r' % PUBLISHER, '']
    write_atomic(AUTHZ, '\n'.join(rules))
    seasons = [n for n in repositories() if SEASON.match(n)]
    catalog = {
        'version': 1,
        'active': state['active'],
        'robots': [{'name': n, 'uuid': uuid(n), 'archived': n in state['archived'], 'master': state.get('masters', {}).get(n)} for n in seasons],
        'library': {'name': LIBRARY, 'uuid': uuid(LIBRARY)} if LIBRARY in repositories() else None,
        # Newest published student installer; the add-in offers it when it is newer than itself.
        'addin': state.get('addin'),
        # The team's SOLIDWORKS version (a year). A newer SOLIDWORKS would save files older ones can't open, so the add-in
        # won't edit or submit team CAD from it.
        'solidworks': state.get('solidworks'),
    }
    write_atomic(CATALOG, json.dumps(catalog, indent=2) + '\n', 0o644)


def install_hooks(name):
    hooks = os.path.join(REPOS, name, 'hooks')
    for hook in ('pre-commit', 'pre-lock', 'pre-unlock'):
        shutil.copyfile(os.path.join(HOOKS, hook), os.path.join(hooks, hook))
        os.chmod(os.path.join(hooks, hook), 0o755)


def create_repository(name, folders, author, message):
    path = os.path.join(REPOS, name)
    if os.path.exists(path):
        raise Refused(name + ' already exists.')
    run('svnadmin', 'create', path)
    install_hooks(name)
    if not folders:
        return
    args = ['svnmucc', '--non-interactive', '--username', author, '-m', message, '-U', 'file://' + path]
    for folder in folders:
        args += ['mkdir', folder]
    run(*args)


def create_test_season(name, source):
    """A full copy of a season (files and history, no locks) for release testing; removable afterwards."""
    if not SEASON.match(name) or name in repositories():
        raise Refused(name + ' must be a new name like 2099-Robot.')
    if source not in repositories() or not SEASON.match(source):
        raise Refused('Unknown season ' + source + '.')
    path = os.path.join(REPOS, name)
    run('svnadmin', 'hotcopy', os.path.join(REPOS, source), path)
    run('svnadmin', 'setuuid', path)  # Its own identity: add-ins never mistake it for the real season.
    for lock in locks(name):
        run('svnadmin', 'rmlocks', path, lock['path'])
    install_hooks(name)
    state = load_state()
    state.setdefault('test_seasons', []).append(name)
    if source in state.get('masters', {}):
        state['masters'][name] = state['masters'][source]
    save_state(state)
    return youngest(name)


def remove_test_season(name):
    state = load_state()
    if name not in state.get('test_seasons', []):
        raise Refused(name + ' is not a test season, so it is never removed this way.')
    if name == state['active']:
        raise Refused('Make another season active first.')
    stamp = time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())
    os.rename(os.path.join(REPOS, name), os.path.join(REPOS, '.deleted-%s-%s' % (name, stamp)))
    state['test_seasons'].remove(name)
    state.get('masters', {}).pop(name, None)
    state['archived'] = [n for n in state['archived'] if n != name]
    save_state(state)


def has_files(name):
    """True once a season holds any file. Only file-less seasons may be deleted."""
    return any(line and not line.endswith('/') for line in run('svnlook', 'tree', '--full-paths', os.path.join(REPOS, name)).splitlines())


CAD_PATTERNS = ('[Ss][Ll][Dd][Pp][Rr][Tt]', '[Ss][Ll][Dd][Aa][Ss][Mm]', '[Ss][Ll][Dd][Dd][Rr][Ww]')


def import_season(name, directory, author, message):
    """Creates a season from an existing folder tree exactly as it is, with lock properties on every CAD file."""
    if not SEASON.match(name):
        raise Refused('Season names look like 2026-Robot.')
    if not os.path.isdir(directory) or not any(files for _, _, files in os.walk(directory)):
        raise Refused('Nothing to import in ' + directory)
    create_repository(name, [], author, message)
    options = ['--config-option', 'config:miscellany:enable-auto-props=yes', '--config-option', 'config:miscellany:global-ignores=']
    for pattern in CAD_PATTERNS:
        options += ['--config-option', 'config:auto-props:*.%s=svn:needs-lock=*;svn:mime-type=application/octet-stream' % pattern]
    run('svn', 'import', '--non-interactive', '--no-auth-cache', '--username', author, '-m', message, *options,
        directory, 'file://' + os.path.join(REPOS, name))
    return verify_import(name, directory)


def verify_import(name, directory):
    """Every file byte-identical in the repository, and every CAD file carries the lock properties."""
    repo = os.path.join(REPOS, name)
    count = 0
    for root, _, names in os.walk(directory):
        for filename in names:
            local = os.path.join(root, filename)
            relative = os.path.relpath(local, directory).replace(os.sep, '/')
            stored = subprocess.run(['svnlook', 'cat', repo, relative], capture_output=True)
            with open(local, 'rb') as handle:
                if stored.returncode != 0 or stored.stdout != handle.read():
                    raise Refused('Imported copy of %s does not match. The season was left in place for inspection.' % relative)
            if relative.lower().endswith(CAD):
                if run('svnlook', 'propget', repo, 'svn:needs-lock', relative).strip() != '*':
                    raise Refused('%s is missing its lock property.' % relative)
            count += 1
    return count


def ensure():
    """Container start: hooks everywhere, a Library repository, consistent generated files."""
    with Locked():
        if LIBRARY not in repositories():
            create_repository(LIBRARY, LIBRARY_FOLDERS, 'joco-admin', 'Create reusable parts library')
        for name in repositories():
            install_hooks(name)
        if not os.path.exists(SECRET):
            write_atomic(SECRET, secrets.token_hex(32), 0o600)
        state = load_state()
        state['archived'] = [n for n in state['archived'] if n in repositories()]
        save_state(state)


# ---------- repository queries ----------

def youngest(name):
    return int(run('svnlook', 'youngest', os.path.join(REPOS, name)))


def locks(name):
    result, current = [], None
    for line in run('svnadmin', 'lslocks', os.path.join(REPOS, name)).splitlines():
        if line.startswith('Path: '):
            current = {'repo': name, 'path': line[6:]}
            result.append(current)
        elif current and line.startswith('Owner: '):
            current['owner'] = line[7:]
        elif current and line.startswith('Created: '):
            current['created'] = line[9:].split(' (')[0]
    return result


def activity(names, limit=15):
    entries = []
    for name in names:
        root = ElementTree.fromstring(run('svn', 'log', '--xml', '-v', '-l', str(limit), 'file://' + os.path.join(REPOS, name)))
        for entry in root.findall('logentry'):
            entries.append({
                'repo': name, 'rev': int(entry.get('revision')),
                'author': entry.findtext('author') or '', 'date': (entry.findtext('date') or '')[:16].replace('T', ' '),
                'msg': (entry.findtext('msg') or '').strip(),
                'files': [p.text for p in entry.findall('paths/path') if p.get('kind') == 'file'],
            })
    return sorted(entries, key=lambda e: e['date'], reverse=True)[:limit]


def files(name):
    listing = run('svnlook', 'tree', '--full-paths', os.path.join(REPOS, name))
    return [p for p in listing.splitlines() if p and not p.endswith('/') and p.lower().endswith(CAD)]


def users():
    with open(USERS) as handle:
        return sorted(line.split(':', 1)[0] for line in handle if ':' in line)


def clean_path(text):
    parts = [p.strip() for p in text.replace('\\', '/').split('/') if p.strip()]
    if not parts or not all(SEGMENT.match(p) for p in parts):
        raise Refused('Use folder and file names with letters, numbers, spaces, and _ ( ) . & + , - only.')
    return '/'.join(parts)


def add_to_library(entries, author, message):
    """entries: [(library path, local file)]. New files only; changing existing parts needs Edit/Submit."""
    existing = set(run('svnlook', 'tree', '--full-paths', os.path.join(REPOS, LIBRARY)).splitlines())
    args = ['svnmucc', '--non-interactive', '--username', author, '-m', message, '-U', 'file://' + os.path.join(REPOS, LIBRARY)]
    made = set()
    for target, local in entries:
        if not target.lower().endswith(CAD):
            raise Refused(target + ' is not a SOLIDWORKS part, assembly, or drawing.')
        if target in existing or target.lower() in {p.lower() for p in existing}:
            raise Refused(target + ' already exists in the library. Update it with Edit and Submit instead.')
        parts = target.split('/')
        for i in range(1, len(parts)):
            folder = '/'.join(parts[:i])
            if folder + '/' not in existing and folder not in made:
                args += ['mkdir', folder]
                made.add(folder)
        args += ['put', local, target, 'propset', 'svn:needs-lock', '*', target,
                 'propset', 'svn:mime-type', 'application/octet-stream', target]
    run(*args)


# ---------- undo a submit ----------

def changed_paths(repo, rev):
    """[(action letter, path, is_dir)] for one revision, from svnlook."""
    result = []
    for line in run('svnlook', 'changed', '-r', str(rev), os.path.join(REPOS, repo)).splitlines():
        if len(line) > 4:
            path = line[4:]
            result.append((line[0], path.rstrip('/'), path.endswith('/')))
    return result


def undo_plan(repo, rev):
    """Checks a revision can be undone safely; returns its changes. Never touches files changed again later."""
    if repo not in repositories():
        raise Refused('Unknown repository.')
    if rev < 2 or rev > youngest(repo):
        raise Refused('That revision cannot be undone.')
    changes = changed_paths(repo, rev)
    if not changes:
        raise Refused('r%d changed no files (only properties or nothing).' % rev)
    repo_path = os.path.join(REPOS, repo)
    later = []
    for action, path, is_dir in changes:
        if action == 'D':
            continue
        try:
            history = run('svnlook', 'history', '--limit', '1', repo_path, '/' + path).splitlines()
        except Refused:
            later.append(path)  # Gone now, so something later removed it.
            continue
        latest = next((int(line.split()[0]) for line in history if line.strip() and line.split()[0].isdigit()), rev)
        if latest != rev:
            later.append(path)
    if later:
        raise Refused('Later submits changed %s. Undo those first (newest first), or ask the student to fix it with Edit/Submit.' % ', '.join(later[:5]))
    held = [l for l in locks(repo) if any(l['path'].lstrip('/') == p or l['path'].lstrip('/').startswith(p + '/') for _, p, _ in changes)]
    if held:
        raise Refused('%s is locked by %s. Ask them to Submit or release it first.' % (held[0]['path'], held[0].get('owner', '?')))
    return changes


def undo_submit(user, repo, rev):
    # Pinned to the revision the checks looked at: if a student submits in between, the undo is out of date and
    # fails instead of replacing their newer work.
    head = youngest(repo)
    changes = undo_plan(repo, rev)
    url = 'file://' + os.path.join(REPOS, repo)
    args = ['svnmucc', '--non-interactive', '--username', user, '--with-revprop', 'joco:mentor-undo=%d' % rev,
            '-m', 'Undo r%d (by %s from the admin page)' % (rev, user), '-r', str(head), '-U', url]
    removed_dirs = []
    for action, path, is_dir in sorted(changes, key=lambda c: c[1]):
        if any(path.startswith(d + '/') for d in removed_dirs):
            continue  # Goes away with its added parent folder.
        if action == 'A':
            args += ['rm', path]
            if is_dir:
                removed_dirs.append(path)
        elif action == 'D':
            args += ['cp', str(rev - 1), path, path]
        elif not is_dir:
            # Content and properties exactly as they were before the submit, keeping history.
            args += ['rm', path, 'cp', str(rev - 1), path, path]
    try:
        output = run(*args)
    except Refused as exc:
        if youngest(repo) != head:
            raise Refused('Someone submitted while you were undoing r%d, so nothing was changed. Look at Recent submits and try again.' % rev) from exc
        raise
    match = re.search(r'r(\d+) committed', output)
    return 'Undid r%d in %s as new revision r%s. Students get the previous versions on their next Update.' % (rev, repo, match.group(1) if match else '?')


